package lockin.fleetflow.Vehicules.services;

import lockin.fleetflow.Vehicules.domain.Maintenance;
import lockin.fleetflow.Vehicules.domain.MaintenanceStatus;
import lockin.fleetflow.Vehicules.domain.MaintenanceType;
import lockin.fleetflow.Vehicules.exception.ResourceNotFoundException;
import lockin.fleetflow.Vehicules.repository.IMaintenanceRepo;
import lockin.fleetflow.Vehicules.web.dto.MaintenanceDTO;
import lockin.fleetflow.Vehicules.web.mapper.IMaintenanceMapper;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.util.List;

@Service
@RequiredArgsConstructor
public class MaintenanceServiceImpl implements IMaintenanceService {

    private final IMaintenanceRepo maintenanceRepo;
    private final IMaintenanceMapper maintenanceMapper;

    @Override
    public MaintenanceDTO create(MaintenanceDTO maintenanceDTO) {
        Maintenance maintenance = maintenanceMapper.toEntity(maintenanceDTO);
        maintenance.setId(null); // Ensure fresh ID is generated by database
        Maintenance saved = maintenanceRepo.save(maintenance);
        return maintenanceMapper.toDTO(saved);
    }

    @Override
    public MaintenanceDTO findById(String id) {
        Maintenance maintenance = maintenanceRepo.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Maintenance", id));
        return maintenanceMapper.toDTO(maintenance);
    }

    @Override
    public List<MaintenanceDTO> findAll() {
        return maintenanceMapper.toDTOList(maintenanceRepo.findAll());
    }

    @Override
    public MaintenanceDTO update(String id, MaintenanceDTO maintenanceDTO) {
        if (!maintenanceRepo.existsById(id)) {
            throw new ResourceNotFoundException("Maintenance", id);
        }
        Maintenance maintenance = maintenanceMapper.toEntity(maintenanceDTO);
        maintenance.setId(id);
        return maintenanceMapper.toDTO(maintenanceRepo.save(maintenance));
    }

    @Override
    public void deleteById(String id) {
        if (!maintenanceRepo.existsById(id)) {
            throw new ResourceNotFoundException("Maintenance", id);
        }
        maintenanceRepo.deleteById(id);
    }

    @Override
    public List<MaintenanceDTO> findByVehicleId(String vehicleId) {
        return maintenanceMapper.toDTOList(maintenanceRepo.findByVehicleIdOrderByMaintenanceDateDesc(vehicleId));
    }

    @Override
    public List<MaintenanceDTO> findByStatus(MaintenanceStatus status) {
        return maintenanceMapper.toDTOList(maintenanceRepo.findByStatus(status));
    }

    @Override
    public List<MaintenanceDTO> findByType(MaintenanceType type) {
        return maintenanceMapper.toDTOList(maintenanceRepo.findByType(type));
    }
}
