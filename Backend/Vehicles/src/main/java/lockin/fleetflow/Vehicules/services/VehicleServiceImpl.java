package lockin.fleetflow.Vehicules.services;

import lockin.fleetflow.Vehicules.domain.Vehicle;
import lockin.fleetflow.Vehicules.domain.VehicleStatus;
import lockin.fleetflow.Vehicules.exception.ResourceNotFoundException;
import lockin.fleetflow.Vehicules.repository.IVehicleRepo;
import lockin.fleetflow.Vehicules.web.dto.VehicleDTO;
import lockin.fleetflow.Vehicules.web.mapper.IVehicleMapper;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.util.List;

@Service
@RequiredArgsConstructor
public class VehicleServiceImpl implements IVehicleService {

    private final IVehicleRepo vehicleRepo;
    private final IVehicleMapper vehicleMapper;

    @Override
    public VehicleDTO create(VehicleDTO vehicleDTO) {
        Vehicle vehicle = vehicleMapper.toEntity(vehicleDTO);
        vehicle.setId(null); // Ensure fresh ID is generated by database
        Vehicle saved = vehicleRepo.save(vehicle);
        return vehicleMapper.toDTO(saved);
    }

    @Override
    public VehicleDTO findById(String id) {
        Vehicle vehicle = vehicleRepo.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Vehicle", id));
        return vehicleMapper.toDTO(vehicle);
    }

    @Override
    public List<VehicleDTO> findAll() {
        return vehicleMapper.toDTOList(vehicleRepo.findAll());
    }

    @Override
    public VehicleDTO update(String id, VehicleDTO vehicleDTO) {
        if (!vehicleRepo.existsById(id)) {
            throw new ResourceNotFoundException("Vehicle", id);
        }
        Vehicle vehicle = vehicleMapper.toEntity(vehicleDTO);
        vehicle.setId(id);
        return vehicleMapper.toDTO(vehicleRepo.save(vehicle));
    }

    @Override
    public void deleteById(String id) {
        if (!vehicleRepo.existsById(id)) {
            throw new ResourceNotFoundException("Vehicle", id);
        }
        vehicleRepo.deleteById(id);
    }

    @Override
    public VehicleDTO findByRegistration(String registration) {
        Vehicle vehicle = vehicleRepo.findByRegistration(registration)
                .orElseThrow(() -> new ResourceNotFoundException("Vehicle with registration " + registration, registration));
        return vehicleMapper.toDTO(vehicle);
    }

    @Override
    public List<VehicleDTO> findByBrand(String brand) {
        return vehicleMapper.toDTOList(vehicleRepo.findByBrand(brand));
    }

    @Override
    public List<VehicleDTO> findByStatus(VehicleStatus status) {
        return vehicleMapper.toDTOList(vehicleRepo.findByStatus(status));
    }
}
